func TestADeferredCancelIsNotACallToEveryFuncInTheModule(t *testing.T) {
	p := repo(t, map[string]string{
		"pay/pay.go": `package pay

import (
	"context"
	"database/sql"
	"time"
)

type Store struct{ DB *sql.DB }

func (s *Store) Charge(ctx context.Context, id string) error {
	ctx, cancel := context.WithTimeout(ctx, time.Second)
	defer cancel()
	_, err := s.DB.ExecContext(ctx, "insert into charges(id) values($1)", id)
	return err
}
`,
		"gw/pay.pb.gw.go": `// Code generated by protoc-gen-grpc-gateway. DO NOT EDIT.

package gw

import "net/http"

func RegisterPayHandlerFromEndpoint() {
	defer func() { http.Get("http://upstream/close") }()
}
`,
		"hooks/hooks.go": `package hooks

var onPaid = []func(){audit}

func audit() {}

func Fire() {
	for _, h := range onPaid {
		h()
	}
}
`,
		"cmd/app/main.go": `package main

import (
	"context"
	"net/http"

	"example.com/m/gw"
	"example.com/m/hooks"
	"example.com/m/pay"
)

func main() {
	go func() { http.Get("http://upstream/health") }()
	gw.RegisterPayHandlerFromEndpoint()
	hooks.Fire()
	_ = (&pay.Store{}).Charge(context.Background(), "x")
}
`,
	})
	const charge = "example.com/m/pay#(*Store).Charge"
	flow, err := p.Flow([]fact.EntryPoint{{Pkg: "example.com/m/pay", Symbol: "(*Store).Charge"}})
	if err != nil {
		t.Fatal(err)
	}
	var reached []string
	for id := range flow.Nodes {
		reached = append(reached, id)
	}
	if !slices.Equal(reached, []string{charge}) {
		t.Errorf("reached %v: the CancelFunc was linked to every func() in the module — main, its goroutine, the gateway's registration — so a wallet flow grew from 284 functions to 1248", reached)
	}
	if callees := p.Callees(charge); len(callees) != 0 {
		t.Errorf("Charge calls no module function, got %+v", callees)
	}
	for _, s := range flow.Seams {
		if s.Kind == fact.SeamHTTP {
			t.Errorf("seam %+v: an HTTP call in a function the flow never runs", s)
		}
	}
	if f, _ := p.Function(charge); !slices.Equal(f.Facts.Reaches, []fact.SeamKind{fact.SeamDB}) {
		t.Errorf("Charge reaches %v; through the cancel it reached whatever main reaches", f.Facts.Reaches)
	}

	var fire []fact.Edge
	for _, e := range p.Callees("example.com/m/hooks#Fire") {
		if e.To == "example.com/m/hooks#audit" {
			fire = append(fire, e)
		}
	}
	if len(fire) != 1 || fire[0].Certainty != fact.Likely {
		t.Errorf("Fire -> audit = %+v: a func() the module stores and calls is still followed, narrowed by VTA", fire)
	}
}

// goPGMigrations is a module shaped like the wallet service: go-pg migrations
// numbered without zero padding and written partly through Sprintf helpers, a
// test package that resets the database, a metrics package whose Register is
// not a migration, and ORM tags that disagree with the migrations.
func goPGMigrations() map[string]string {
	migration := func(up, down string) string {
		reg := "migrations.MustRegisterTx(func(db migrations.DB) error {\n\t\t_, err := db.Exec(" + up + ")\n\t\treturn err\n\t}"
		if down != "" {
			reg += ", func(db migrations.DB) error {\n\t\t_, err := db.Exec(" + down + ")\n\t\treturn err\n\t}"
		}
		return "package migrations\n\nimport \"github.com/go-pg/migrations/v8\"\n\nfunc init() {\n\t" + reg + ")\n}\n"
	}
	return map[string]string{
		"go.mod":                       "module example.com/m\n\ngo 1.22\n\nrequire github.com/go-pg/migrations/v8 v8.0.0\n\nreplace github.com/go-pg/migrations/v8 => ./thirdparty/migrations\n",
		"thirdparty/migrations/go.mod": "module github.com/go-pg/migrations/v8\n\ngo 1.22\n",
		"thirdparty/migrations/migrations.go": `package migrations

type DB interface {
	Exec(query any, params ...any) (any, error)
}

func MustRegisterTx(fns ...func(DB) error) {}
`,
		"db/migrations/helpers.go": `package migrations

import "fmt"

func addColumn(table, column, typ string) string {
	return fmt.Sprintf("ALTER TABLE %s ADD %s %s", table, column, typ)
}

func dropColumn(table, column string) string {
	return fmt.Sprintf("ALTER TABLE %s DROP %s", table, column)
}

func renameIndex(from, to string) string {
	return fmt.Sprintf("alter index %s rename to %s", from, to)
}

func dropConstraint(table, name string) string {
	return "ALTER TABLE " + table + " DROP CONSTRAINT " + name
}
`,
		"db/migrations/1_wallets.go":         migration("`CREATE TABLE wallets (id uuid PRIMARY KEY, number text UNIQUE, user_id uuid)`", "`DROP TABLE wallets`"),
		"db/migrations/2_payments.go":        migration("`CREATE TABLE payments (id uuid PRIMARY KEY, wallet_id uuid)`", "`DROP TABLE payments`"),
		"db/migrations/10_payments_rrn.go":   migration(`addColumn("payments", "rrn", "varchar(64)")`, `dropColumn("payments", "rrn")`),
		"db/migrations/11_wallets_number.go": migration(`renameIndex("wallets_number_key", "wallets_num_key") + "; " + dropConstraint("wallets", "wallets_num_key")`, ""),
		"test/setup.go": `package test

import "database/sql"

func Reset(db *sql.DB) error {
	_, err := db.Exec(` + "`" + `
		DROP TABLE IF EXISTS wallets CASCADE;
		DROP TABLE IF EXISTS payments CASCADE;
	` + "`" + `)
	return err
}
`,
		"metrics/prom/prom.go": "package prom\n\nfunc Register(c any) error { return nil }\n",
		"metrics/metrics.go": `package metrics

import "example.com/m/metrics/prom"

var Requests struct{}

func init() { _ = prom.Register(Requests) }
`,
		"domain/wallet.go": `package domain

type Wallet struct {
	tableName struct{} ` + "`pg:\"wallets\"`" + `
	ID        string   ` + "`pg:\",pk\"`" + `
	Number    string   ` + "`pg:\",unique\"`" + `
	UserID    string   ` + "`pg:\",unique\"`" + `
}
`,
	}
}

func TestGoMigrationsLeaveTheSchemaTheyBuild(t *testing.T) {
	p := repo(t, goPGMigrations())
	infra := p.Infra()
	for _, table := range []string{"wallets", "payments"} {
		if !infra.HasTable(table) {
			t.Fatalf("no %s table: test/setup.go's reset dropped every table the migrations created; tables = %+v", table, infra.Tables)
		}
	}
	if !infra.HasColumn("payments", "rrn") {
		t.Errorf("payments.rrn missing: 10_ ran before 2_ (file names compared as strings), and addColumn(...) was not read; columns = %+v", infra.ColumnsOf("payments"))
	}
	if cov, ok := infra.UniqueOn("wallets", "number"); ok {
		t.Errorf("migration 11 renames the index and drops it under its new name, yet %+v still covers wallets.number", cov.Constraint)
	}
	if cov, ok := infra.UniqueOn("wallets", "user_id"); ok {
		t.Errorf("only a pg tag says user_id is unique, and the migrations built this table: %+v", cov.Constraint)
	}
	if slices.Contains(infra.MigrationDirs, "test") {
		t.Errorf("dirs = %v: a test reset is not a migration", infra.MigrationDirs)
	}
	if infra.MigrationsTotal != 4 || infra.MigrationsWithDown != 3 || infra.MigrationFiles != 4 {
		t.Errorf("total %d, with down %d, files %d; want 4, 3, 4 (prom.Register is not a migration, helpers.go holds no statement)",
			infra.MigrationsTotal, infra.MigrationsWithDown, infra.MigrationFiles)
	}
	fs := findings(p.Findings(), "MIGRATION-NO-DOWN")
	if len(fs) != 1 || fs[0].Title != "1 of 4 migrations cannot be rolled back" {
		t.Errorf("MIGRATION-NO-DOWN = %+v", fs)
	}
}

func TestGoDDLOutsideMigrationsOnlyAdds(t *testing.T) {
	p := repo(t, map[string]string{
		"store/schema.go": `package store

import "database/sql"

const schema = ` + "`" + `
CREATE TABLE IF NOT EXISTS payments (id text PRIMARY KEY, idem_key text);
CREATE UNIQUE INDEX IF NOT EXISTS payments_idem_key ON payments (idem_key);
` + "`" + `

func Init(db *sql.DB) error { _, err := db.Exec(schema); return err }
`,
		"store/testing.go": `package store

import "database/sql"

func Reset(db *sql.DB) error {
	_, err := db.Exec("DROP INDEX payments_idem_key; DROP TABLE payments")
	return err
}
`,
	})
	infra := p.Infra()
	if _, ok := infra.UniqueOn("payments", "idem_key"); !ok {
		t.Fatalf("with no migrations, the schema is what the code creates, and a reset helper does not undo it; infra = %+v", infra)
	}
}

func TestAPrimaryKeyIsNotAnIdempotencyKeyForBeingOne(t *testing.T) {
	keys := fixture(t, "walletsvc").IdempotencyKeys()
	if c, ok := keys.Decided(); ok {
		t.Fatalf("decided %s, proof %v: a WHERE clause on wallets.id and the primary key are what every table has", c, c.Proof)
	}
	if c, ok := keys.Find("Wallet", "ID"); ok && c.Credible() {
		t.Errorf("Wallet.ID is credible: %s %v", c, c.Proof)
	}
}

